// The shell halves of `bb completion`. They are shell, not TypeScript, on purpose: completion runs on
// every Tab, and starting node would cost more than everything these scripts do put together.
// @@NAME@@ markers are filled in by ./index.ts from the commander program, so flags, subcommands and
// their descriptions cannot drift from the CLI.
//
// Inside these template literals a shell `${` is written `\${` and every backslash is doubled.

/** Helpers both shells share, written in the subset of syntax that zsh and bash 3.2 agree on. */
export const COMMON = `# --- shared by the zsh and bash scripts: plain git and gh, no node, nothing printed on failure ---

# Refs git can resolve in directory $1, one per line: branches, remote branches, tags, anything
# else under refs/, and HEAD. Symbolic refs (origin/HEAD) come out as blank lines.
__bb_refs() {
  git -C "$1" for-each-ref --format='%(if)%(symref)%(then)%(else)%(refname:short)%(end)' 2> /dev/null && printf 'HEAD\\n'
}

# Rewrite the pull request cache $1 for the repository in directory $2. Runs detached from the
# shell (no job notice, no output) and gives gh ten seconds. A failed or killed gh leaves a cache
# with a timestamp and no pull requests, so a broken gh is retried once a minute, not on every Tab.
__bb_pr_refresh() {
  ( (
    cd "$2" || exit 0
    mkdir -p "\${1%/*}" || exit 0
    date +%s > "$1.pending"
    GH_PROMPT_DISABLED=1 GH_NO_UPDATE_NOTIFIER=1 gh pr list --limit 50 --json number,title,headRefName \\
      --template '{{range .}}{{.number}}{{"\\t"}}{{.title}} ({{.headRefName}}){{"\\n"}}{{end}}' > "$1.body.$$" < /dev/null &
    job=$!
    ( sleep 10; kill "$job" ) &
    watchdog=$!
    wait "$job" || : > "$1.body.$$"
    kill "$watchdog"
    { date +%s; cat "$1.body.$$"; } > "$1.new.$$" && mv -f "$1.new.$$" "$1"
    rm -f "$1.body.$$" "$1.new.$$" "$1.pending"
  ) > /dev/null 2>&1 & )
}

# Open pull requests of the repository in directory $1, as "number<TAB>title (branch)" lines in
# __bb_pr_lines. They come from a per-repository cache file, so this does not wait on the network:
# a cache older than a minute is still used, and refreshed in the background for next time. The one
# exception is the first Tab in a repository, which gives gh up to a second to fill the cache
# (__bb_nap, a tenth of a second, is defined per shell).
# Nothing happens, silently, without gh, outside a repository, or with BB_COMPLETION_PRS=0.
__bb_prs() {
  __bb_pr_lines=
  [ "\${BB_COMPLETION_PRS:-1}" != 0 ] || return 0
  command -v gh > /dev/null 2>&1 || return 0
  local gitdir key cache now stamp pending entry first tries
  gitdir=$(git -C "$1" rev-parse --absolute-git-dir 2> /dev/null) || return 0
  [ -n "$gitdir" ] || return 0
  key=$(printf '%s' "$gitdir" | cksum 2> /dev/null)
  key=\${key%% *}
  [ -n "$key" ] || return 0
  cache="\${XDG_CACHE_HOME:-$HOME/.cache}/baby-bird/completion/prs-$key"
  now=\${EPOCHSECONDS:-$(date +%s)}
  stamp=0
  [ -r "$cache" ] && { IFS= read -r stamp < "$cache"; } 2> /dev/null
  case "$stamp" in '' | *[!0-9]*) stamp=0 ;; esac
  if [ $((now - stamp)) -ge 60 ]; then
    pending=0
    [ -r "$cache.pending" ] && { IFS= read -r pending < "$cache.pending"; } 2> /dev/null
    case "$pending" in '' | *[!0-9]*) pending=0 ;; esac
    if [ $((now - pending)) -ge 15 ]; then
      __bb_pr_refresh "$cache" "$1"
      if [ ! -e "$cache" ]; then
        tries=0
        while [ ! -e "$cache" ] && [ "$tries" -lt 10 ]; do
          __bb_nap
          tries=$((tries + 1))
        done
      fi
    fi
  fi
  [ -r "$cache" ] || return 0
  first=1
  {
    while IFS= read -r entry; do
      if [ "$first" = 1 ]; then
        first=0
        continue
      fi
      case "$entry" in [0-9]*) __bb_pr_lines="$__bb_pr_lines$entry
" ;; esac
    done < "$cache"
  } 2> /dev/null
}

# Subcommands of the command path $1 ("" is bb itself), space separated, in __bb_sub_names.
__bb_subs() {
  case "$1" in
@@SUBS_CASE@@
    *) __bb_sub_names= ;;
  esac
}`;

export const ZSH = `#compdef bb baby-bird
# zsh completion for bb (baby-bird @@VERSION@@). Generated by \`bb completion zsh\`; do not edit.
# Regenerate after upgrading bb. To install, see \`bb completion --help\`.

zmodload -F zsh/datetime p:EPOCHSECONDS 2> /dev/null
zmodload -F zsh/zselect b:zselect 2> /dev/null

@@COMMON@@

# A tenth of a second. A builtin, because running \`sleep\` from a completion widget makes zsh redraw
# the command line. zselect returns 1 when the time is up; anything higher means it is not available.
__bb_nap() {
  zselect -t 10 2> /dev/null
  (( $? <= 1 )) || sleep 0.1
}

__bb_zsh_refs() {
  local -a refs
  local expl
  refs=(\${(f)"$(__bb_refs "$1")"})
  (( $#refs )) || return 1
  _wanted refs expl 'branch, tag or other ref' compadd -a refs
}

__bb_zsh_prs() {
  local -a prs
  local entry tab=$'\\t'
  __bb_prs "$1"
  for entry in \${(f)__bb_pr_lines}; do
    prs+=("\${entry%%\${tab}*}:\${\${entry#*\${tab}}//:/\\\\:}")
  done
  (( $#prs )) || return 1
  compset -P '\\#'
  # -V keeps gh's order (newest first) instead of sorting 10 before 9.
  _describe -V -t pull-requests 'open pull request' prs
}

# Options of the command path $1, as "flag:description", in the caller's opts.
__bb_zsh_opts() {
  case "$1" in
@@ZSH_OPTS_CASE@@
    *) opts=() ;;
  esac
}

# Subcommands of the command path $1, as "name:description", in the caller's subs.
__bb_zsh_subs() {
  case "$1" in
@@ZSH_SUBS_CASE@@
    *) subs=() ;;
  esac
}

_bb() {
  local cur=$words[CURRENT] prev=$words[CURRENT-1] cmd= dir=. word expl
  local -i i npos=0 ret=1
  local -a opts subs

  # Walk the words before the cursor: -C <dir>, the subcommand, and how many positionals came first.
  for (( i = 2; i < CURRENT; i++ )); do
    word=$words[i]
    case $word in
      -C | --cwd)
        (( i + 1 < CURRENT )) && dir=\${(Q)words[i+1]}
        (( i += 1 ))
        ;;
      --cwd=*) dir=\${(Q)word#--cwd=} ;;
      -*) [[ " @@VALUE_FLAGS@@ " == *" $word "* ]] && (( i += 1 )) ;;
      *)
        __bb_subs "$cmd"
        if [[ " $__bb_sub_names " == *" $word "* ]]; then
          cmd="\${cmd:+$cmd }$word"
          npos=0
        else
          (( npos += 1 ))
        fi
        ;;
    esac
  done
  dir=\${dir/#\\~/$HOME}

  case $prev in
    -C | --cwd) _directories; return ;;
    --preset) _wanted presets expl 'preset' compadd @@PRESETS@@; return ;;
    --base | --head) __bb_zsh_refs "$dir"; return ;;
    --pr) __bb_zsh_prs "$dir"; return ;;
    --section) _message 'section number'; return ;;
  esac

  if [[ $cur == -* ]]; then
    __bb_zsh_opts "$cmd"
    _describe -o 'option' opts
    return
  fi

  if (( npos > 0 )); then
    [[ $cmd == ask ]] && _message 'opening message'
    return 1
  fi

  __bb_zsh_subs "$cmd"
  (( $#subs )) && _describe -t commands 'command' subs && ret=0

  case $cmd in
    '' | ask)
      # What to tour: a ref, the second half of A..B / A...B, or a pull request number.
      if compset -P '*...' || compset -P '*..'; then
        __bb_zsh_refs "$dir" && ret=0
      else
        __bb_zsh_refs "$dir" && ret=0
        [[ $PREFIX =~ '^#?[0-9]*$' ]] && __bb_zsh_prs "$dir" && ret=0
      fi
      ;;
    completion) _wanted shells expl 'shell' compadd @@SHELLS@@ && ret=0 ;;
  esac
  return ret
}

if [[ $funcstack[1] == _bb ]]; then
  # Autoloaded from fpath as _bb: the definitions above replaced this stub, so run the real one.
  _bb "$@"
elif (( $+functions[compdef] )); then
  compdef _bb bb baby-bird
else
  print -u2 'bb completion: compinit has not run yet. Put "autoload -Uz compinit && compinit" before this line.'
fi
`;

export const BASH = `# bash completion for bb (baby-bird @@VERSION@@). Generated by \`bb completion bash\`; do not edit.
# Regenerate after upgrading bb. To install, see \`bb completion --help\`.

@@COMMON@@

__bb_nap() {
  sleep 0.1
}

# Options of the command path $1, space separated, in __bb_opt_names.
__bb_bash_opts() {
  case "$1" in
@@BASH_OPTS_CASE@@
    *) __bb_opt_names= ;;
  esac
}

# Add every line of $1 that starts with $2 to COMPREPLY, with $3 in front. Candidates are matched
# by hand, never through \`compgen -W\`, which would expand a branch named \`$(...)\`. Names with
# characters the shell would act on are left out, because bash inserts candidates unquoted.
__bb_bash_add() {
  local candidate
  while IFS= read -r candidate; do
    [ -n "$candidate" ] || continue
    case "$candidate" in *[!A-Za-z0-9._/@+=,%-]*) continue ;; esac
    case "$candidate" in "$2"*) COMPREPLY[\${#COMPREPLY[@]}]="$3$candidate" ;; esac
  done << __BB_EOF__
$1
__BB_EOF__
}

# Open pull request numbers for directory $1, one per line, in __bb_pr_numbers.
__bb_bash_pr_numbers() {
  local entry tab=$'\\t'
  __bb_pr_numbers=
  __bb_prs "$1"
  while IFS= read -r entry; do
    [ -n "$entry" ] && __bb_pr_numbers="$__bb_pr_numbers\${entry%%"$tab"*}
"
  done << __BB_EOF__
$__bb_pr_lines
__BB_EOF__
}

_bb() {
  local cur prev word cmd= dir=. i=1 npos=0 prefix
  COMPREPLY=()
  cur=\${COMP_WORDS[COMP_CWORD]}
  prev=
  [ "$COMP_CWORD" -ge 1 ] && prev=\${COMP_WORDS[COMP_CWORD-1]}

  # Walk the words before the cursor: -C <dir>, the subcommand, and how many positionals came first.
  while [ "$i" -lt "$COMP_CWORD" ]; do
    word=\${COMP_WORDS[i]}
    case "$word" in
      -C | --cwd)
        [ $((i + 1)) -lt "$COMP_CWORD" ] && dir=\${COMP_WORDS[i+1]}
        i=$((i + 1))
        ;;
      -*) case " @@VALUE_FLAGS@@ " in *" $word "*) i=$((i + 1)) ;; esac ;;
      *)
        __bb_subs "$cmd"
        case " $__bb_sub_names " in
          *" $word "*)
            cmd="\${cmd:+$cmd }$word"
            npos=0
            ;;
          *) npos=$((npos + 1)) ;;
        esac
        ;;
    esac
    i=$((i + 1))
  done
  case "$dir" in "~"*) dir="$HOME\${dir#"~"}" ;; esac

  case "$prev" in
    -C | --cwd)
      COMPREPLY=($(compgen -d -- "$cur"))
      type compopt > /dev/null 2>&1 && compopt -o filenames
      return
      ;;
    --preset)
      __bb_bash_add "$(printf '%s\\n' @@PRESETS@@)" "$cur" ''
      return
      ;;
    --base | --head)
      __bb_bash_add "$(__bb_refs "$dir")" "$cur" ''
      return
      ;;
    --pr)
      __bb_bash_pr_numbers "$dir"
      __bb_bash_add "$__bb_pr_numbers" "\${cur#"#"}" ''
      return
      ;;
    --section) return ;;
  esac

  case "$cur" in
    -*)
      __bb_bash_opts "$cmd"
      __bb_bash_add "$(printf '%s\\n' $__bb_opt_names)" "$cur" ''
      return
      ;;
  esac

  [ "$npos" -eq 0 ] || return

  __bb_subs "$cmd"
  __bb_bash_add "$(printf '%s\\n' $__bb_sub_names)" "$cur" ''

  case "$cmd" in
    '' | ask)
      # What to tour: a ref, the second half of A..B / A...B, or a pull request number.
      case "$cur" in
        *...*) __bb_bash_add "$(__bb_refs "$dir")" "\${cur##*...}" "\${cur%...*}..." ;;
        *..*) __bb_bash_add "$(__bb_refs "$dir")" "\${cur##*..}" "\${cur%..*}.." ;;
        *)
          __bb_bash_add "$(__bb_refs "$dir")" "$cur" ''
          case "\${cur#"#"}" in
            *[!0-9]*) ;;
            *)
              prefix=
              case "$cur" in "#"*) prefix='#' ;; esac
              __bb_bash_pr_numbers "$dir"
              __bb_bash_add "$__bb_pr_numbers" "\${cur#"#"}" "$prefix"
              ;;
          esac
          ;;
      esac
      ;;
    completion) __bb_bash_add "$(printf '%s\\n' @@SHELLS@@)" "$cur" '' ;;
  esac
}

complete -F _bb bb baby-bird
`;
